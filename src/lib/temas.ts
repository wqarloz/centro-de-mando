export function getTema(id: string): Tema {
  return TEMAS.find((t) => t.id === id) ?? TEMAS[0];
}

/** Aplica un tema + modo al documento entero y lo recuerda. */
export function aplicarTema(id: string, modo: Modo): void {
  const tema = getTema(id);
  const vars = aCSSVars(tema[modo]);
  const raiz = document.documentElement;
  for (const [k, v] of Object.entries(vars)) raiz.style.setProperty(k, v);
  raiz.classList.toggle("dark", modo === "oscuro");
  try {
    localStorage.setItem(CLAVES_TEMA.tema, tema.id);
    localStorage.setItem(CLAVES_TEMA.modo, modo);
    localStorage.setItem(CLAVES_TEMA.vars, JSON.stringify(vars));
  } catch {
    // Sin almacenamiento disponible: el tema se aplica igual, solo no se recuerda.
  }
}
