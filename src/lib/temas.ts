/** Convierte una paleta en el mapa de variables CSS que la app lee. */
export function aCSSVars(p: Paleta): Record<string, string> {
  const vars: Record<string, string> = {
    "--fondo": p.fondo,
    "--tarjeta": p.tarjeta,
    "--tarjeta-baja": p.tarjetaBaja,
    "--panel": p.panel,
    "--linea": p.linea,
    "--linea-suave": p.lineaSuave,
    "--linea-fuerte": p.lineaFuerte,
    "--linea-hover": p.lineaHover,
    "--tinta": p.tinta,
    "--tinta-suave": p.tintaSuave,
    "--tinta-muda": p.tintaMuda,
    "--acento": p.acento,
    "--acento-claro": p.acentoClaro,
    "--acento-tinta": p.acentoTinta,
    "--exito": p.exito,
    "--exito-tinta": p.exitoTinta,
    "--peligro": p.peligro,
    "--peligro-tinta": p.peligroTinta,
    "--estado-prospecto": p.estadoProspecto,
    "--estado-confirmado": p.estadoConfirmado,
    "--estado-facturado": p.estadoFacturado,
    "--estado-cancelado": p.estadoCancelado,
    "--brillo": p.brillo,
    "--radius": p.radio,
    "--radio-tarjeta": p.radioTarjeta,
    "--grosor-linea": p.grosor,
    "--sombra-tarjeta": p.sombra,
    "--fuente-display": FUENTES_DISPLAY[p.fuente],
    "--esquema-color": p.esquema,
    // Aliases para los componentes de diálogo/select/toast (shadcn),
    // que hablan el idioma de --background, --card, etc.
    "--background": p.fondo,
    "--foreground": p.tintaSuave,
    "--card": p.tarjeta,
    "--card-foreground": p.tinta,
    "--popover": p.tarjeta,
    "--popover-foreground": p.tinta,
    "--primary": p.acento,
    "--primary-foreground": p.acentoTinta,
    "--secondary": p.panel,
    "--secondary-foreground": p.tinta,
    "--muted": p.panel,
    "--muted-foreground": p.tintaMuda,
    "--accent": p.panel,
    "--accent-foreground": p.tinta,
    "--destructive": p.peligro,
    "--border": p.lineaFuerte,
    "--input": p.lineaFuerte,
    "--ring": p.acento,
  };
  return vars;
}

